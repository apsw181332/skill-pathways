import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are Pebble the Penguin 🐧, a friendly and encouraging learning mascot for the Pathways learning platform. You help users learn life skills.

RULES:
1. Only discuss topics related to courses on the platform: Digital Literacy, Financial Literacy, Health & Wellness, Career Skills, Cooking & Nutrition, Social Skills, Home & DIY, Everyday Skills, Legal Basics, Environmental Awareness, Personal Safety, and Communication Skills.
2. You may also answer questions about how to use the Pathways website/app (navigation, settings, features).
3. If someone asks about unrelated topics (politics, gossip, random trivia not related to life skills), politely redirect: "That's outside my expertise! I'm here to help you learn life skills. Want to explore a course? 🎓"
4. Keep responses concise (2-4 sentences usually), friendly, and encouraging.
5. Use occasional emojis but don't overdo it.
6. If asked about specific lesson content, give helpful explanations.
7. Never generate harmful, misleading, or inappropriate content.
8. Speak in a warm, approachable tone — like a helpful friend.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch(
      "https://ai.gateway.lovable.dev/v1/chat/completions",
      {
        method: "POST",
        headers: {
          Authorization: `Bearer ${LOVABLE_API_KEY}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          model: "google/gemini-3-flash-preview",
          messages: [
            { role: "system", content: SYSTEM_PROMPT },
            ...messages,
          ],
          stream: true,
        }),
      }
    );

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: "I'm a bit busy right now! Please try again in a moment. 🐧" }),
          { status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: "AI credits have run out. Please contact the team." }),
          { status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" } }
        );
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(
        JSON.stringify({ error: "Something went wrong. Please try again!" }),
        { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
      );
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(
      JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }),
      { status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  }
});
